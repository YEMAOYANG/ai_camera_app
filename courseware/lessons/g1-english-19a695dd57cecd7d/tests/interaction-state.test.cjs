const assert = require('node:assert/strict');
const path = require('node:path');
const position = require(path.join(__dirname, '../pages/position.js')).createModel();
assert.equal(position.attempt('on'), 'hint');
assert.equal(position.level, 0);
assert.equal(position.stars, 0);
assert.equal(position.attempt('in'), 'hint');
assert.equal(position.attempt('on'), 'demo');
assert.equal(position.level, 0, 'demonstration does not pass a round');
for (const place of ['under', 'on', 'in']) assert.equal(position.attempt(place), 'correct');
assert.equal(position.done, true);
position.reset();
assert.deepEqual([position.level, position.misses, position.stars, position.done], [0, 0, 0, false]);
const search = require(path.join(__dirname, '../pages/search.js')).createModel();
assert.equal(search.attempt('on'), 'hint');
assert.deepEqual(search.found, [], 'a distractor must not enter the collection');
for (const place of ['under', 'in', 'on']) assert.equal(search.attempt(place), 'correct');
assert.deepEqual(search.found, ['under', 'in', 'on']);
search.reset();
assert.deepEqual(search.found, []);
assert.equal(search.target(), 'under');
const arrange = require(path.join(__dirname, '../pages/arrange.js')).createModel();
assert.equal(arrange.attempt('car', 'on'), 'hint', 'right position with wrong noun fails');
assert.equal(arrange.attempt('bear', 'under'), 'hint', 'right noun with wrong position fails');
assert.equal(arrange.stars, 0);
assert.equal(arrange.attempt('bear', 'on'), 'correct');
assert.equal(arrange.attempt('bear', 'on'), 'already', 'placed objects cannot grant duplicate stars');
assert.equal(arrange.attempt('hat', 'under'), 'correct');
assert.equal(arrange.attempt('car', 'in'), 'correct');
assert.deepEqual(arrange.placed, {bear:'on',hat:'under',car:'in'});
assert.equal(arrange.stars, 3);
arrange.reset();
assert.deepEqual(arrange.placed, {});
assert.equal(arrange.done, false);
console.log('interaction state: wrong/retry/demo/completion/replay passed for all 3 pages');
